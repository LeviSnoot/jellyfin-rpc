use std::{collections::HashSet, env, fs, path::Path};

/// Generates `embedded.rs` in `OUT_DIR`, exposing:
/// - `components::<name>::Styles` with a `&'static str` const per CSS class,
///   replacing `#[css_module]` so no external stylesheet files are needed,
/// - `components::CSS`, every vendored component stylesheet concatenated,
/// - `FONT_<name>`, each `assets/fonts/*.woff2` as a base64 data URI.
fn main() {
    let root = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).to_path_buf();
    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("embedded.rs");

    let mut src = String::from("/// Generated by build.rs. Do not edit.\npub mod components {\n");
    let mut css = String::new();

    // Watch the directories too, so newly added components or fonts trigger a rerun.
    println!(
        "cargo:rerun-if-changed={}",
        root.join("src/components").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        root.join("assets/fonts").display()
    );

    let mut dirs: Vec<_> = fs::read_dir(root.join("src/components"))
        .unwrap()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();

    for dir in dirs {
        let name = dir.file_name().unwrap().to_str().unwrap().to_owned();
        let file = dir.join("style.css");
        if !file.exists() {
            continue;
        }
        println!("cargo:rerun-if-changed={}", file.display());
        let text = fs::read_to_string(&file).unwrap();
        css.push_str(&text);
        css.push('\n');

        src.push_str(&format!(
            "pub mod {name} {{\n    /// Class names for the {name} component.\n    #[allow(dead_code)]\n    pub struct Styles;\n    #[allow(dead_code, non_upper_case_globals)]\n    impl Styles {{\n"
        ));
        let mut seen = HashSet::new();
        for class in class_names(&text) {
            if seen.insert(class.clone()) {
                src.push_str(&format!(
                    "        pub const {}: &str = \"{class}\";\n",
                    class.replace('-', "_")
                ));
            }
        }
        src.push_str("    }\n}\n");
    }

    src.push_str(&format!("pub const CSS: &str = r##\"{css}\"##;\n}}\n"));

    let fonts = root.join("assets/fonts");
    if let Ok(entries) = fs::read_dir(&fonts) {
        let mut files: Vec<_> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
        files.sort();
        for file in files {
            if file.extension().and_then(|e| e.to_str()) != Some("woff2") {
                continue;
            }
            println!("cargo:rerun-if-changed={}", file.display());
            let name = file
                .file_stem()
                .unwrap()
                .to_str()
                .unwrap()
                .replace('-', "_")
                .to_uppercase();
            src.push_str(&format!(
                "/// Data URI for the {name} font.\npub const FONT_{name}: &str = \"data:font/woff2;base64,{}\";\n",
                b64(&fs::read(&file).unwrap())
            ));
        }
    }

    fs::write(&out, src).unwrap();
}

/// Class selectors used in a stylesheet, e.g. `dx-button` from `.dx-button:hover`.
fn class_names(css: &str) -> Vec<String> {
    let bytes = css.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'.'
            && i + 1 < bytes.len()
            && (bytes[i + 1].is_ascii_alphabetic() || bytes[i + 1] == b'_')
        {
            let start = i + 1;
            let mut end = start;
            while end < bytes.len()
                && (bytes[end].is_ascii_alphanumeric() || bytes[end] == b'-' || bytes[end] == b'_')
            {
                end += 1;
            }
            out.push(css[start..end].to_string());
            i = end;
        } else {
            i += 1;
        }
    }
    out
}

fn b64(data: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let n = (chunk[0] as u32) << 16
            | (*chunk.get(1).unwrap_or(&0) as u32) << 8
            | (*chunk.get(2).unwrap_or(&0) as u32);
        out.push(T[(n >> 18) as usize & 63] as char);
        out.push(T[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 {
            T[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            T[n as usize & 63] as char
        } else {
            '='
        });
    }
    out
}
